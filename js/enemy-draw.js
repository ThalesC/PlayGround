'use strict';

function drawEnemy(e) {
  const pos = project(e.x, e.y, 0);
  const f = project(e.face.x, e.face.y, 0);
  const flip = f.x < -0.01 ? -1 : 1;
  const spawnT = e.spawnTime > 0 ? 1 - clamp(e.spawnTime / 0.7, 0, 1) : 1;

  ctx.save();
  ctx.translate(pos.x, pos.y);
  ctx.globalAlpha = e.dead ? clamp(1 - Math.max(0, e.deathTime - 1.2) * 0.5, 0, 1) : spawnT;
  const bob = Math.sin(G.time * 2.4 + e.seed) * 1.5;
  if (e.spawnTime > 0) ctx.translate(0, (1 - spawnT) * 28);
  ctx.scale(flip, 1);

  if (e.dead) {
    drawEnemyCorpse(e, bob);
    ctx.restore();
    return;
  }

  if (e.type === 'husk') drawHusk(e, bob);
  else if (e.type === 'brute') drawBrute(e, bob);
  else if (e.type === 'wraith') drawWraith(e, bob);
  else if (e.type === 'boss') drawBoss(e, bob);

  if (e.flash > 0) {
    ctx.save();
    ctx.globalCompositeOperation = 'lighter';
    ctx.globalAlpha = clamp(e.flash * 4.2, 0, 0.5);
    ctx.fillStyle = '#ffe6bf';
    ctx.beginPath();
    ctx.ellipse(0, -e.height * 0.5, e.r * 0.8, e.height * 0.5, 0, 0, TAU);
    ctx.fill();
    ctx.restore();
  }
  ctx.restore();

  if (e.type !== 'boss' && e.hp < e.maxHp && e.spawnTime <= 0) drawEnemyHealth(e, pos);
}

function drawEnemyCorpse(e, bob) {
  const h = e.height;
  ctx.save();
  ctx.rotate(e.type === 'brute' ? 1.25 : 1.42);
  ctx.globalAlpha *= 0.65;
  ctx.beginPath();
  ctx.ellipse(0, 0, e.r * 1.25, e.r * 0.5, 0, 0, TAU);
  ctx.fillStyle = 'rgba(30, 18, 18, .4)';
  ctx.fill();
  ctx.beginPath();
  ctx.moveTo(-e.r * 0.7, -h * 0.22);
  ctx.lineTo(e.r * 0.9, -h * 0.14);
  ctx.lineTo(e.r * 0.8, h * 0.1);
  ctx.lineTo(-e.r * 0.6, h * 0.14);
  ctx.closePath();
  ctx.fillStyle = e.type === 'wraith' ? 'rgba(38, 58, 55, .6)' : 'rgba(54, 48, 44, .72)';
  ctx.fill();
  ctx.beginPath();
  ctx.arc(e.r * 0.9, -h * 0.2, e.r * 0.32, 0, TAU);
  ctx.fillStyle = 'rgba(98, 90, 78, .6)';
  ctx.fill();
  ctx.restore();
}

function drawEnemyHealth(e, pos) {
  const width = e.type === 'brute' ? 68 : 48;
  const y = pos.y - e.height - 18;
  ctx.save();
  ctx.translate(pos.x - width / 2, y);
  ctx.fillStyle = 'rgba(0, 0, 0, .62)';
  ctx.fillRect(0, 0, width, 4);
  ctx.fillStyle = e.type === 'wraith' ? '#7fe0c3' : e.type === 'brute' ? '#e48b51' : '#c04b3d';
  ctx.fillRect(0, 0, width * clamp(e.hp / e.maxHp, 0, 1), 4);
  ctx.strokeStyle = 'rgba(201, 168, 106, .22)';
  ctx.strokeRect(-0.5, -0.5, width + 1, 5);
  ctx.restore();
}

